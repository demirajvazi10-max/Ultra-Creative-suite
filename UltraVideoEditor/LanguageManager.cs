        /// <summary>v1.4 — text in the language the program is using right now (safe from any thread).</summary>
        public static string T(string key) => GetText(key, CurrentLanguage ?? "en");

        /// <summary>v1.4 — formatted text in the language the program is using right now.</summary>
        public static string F(string key, params object[] args) => string.Format(GetText(key, CurrentLanguage ?? "en"), args);

        public static string GetText(string key, string language = "en")
        {
            if (_translations.ContainsKey(language) && _translations[language].ContainsKey(key))
                return _translations[language][key];

            if (_translations["en"].ContainsKey(key))
                return _translations["en"][key];

            return key.Replace("_", " ").ToUpper();
        }
